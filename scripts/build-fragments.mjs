import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const repo = process.cwd();
const site = path.join(repo, 'site');
const fragments = path.join(site, 'fragments');
const version = new Date().toISOString().slice(0, 10);
const generatedAt = `${version}T00:00:00.000Z`; // deterministic within the release day

fs.mkdirSync(fragments, { recursive: true });

const write = (rel, body) => fs.writeFileSync(path.join(fragments, rel), body.endsWith('\n') ? body : body + '\n');
const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const size = (file) => fs.statSync(file).size;

