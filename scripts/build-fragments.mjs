const fragmentFiles = [
  'README.md', 'LICENSE.md', 'hero.html', 'wake.md', 'love.md', 'youspeak.md', 'kingdom.json', 'links.json', 'deploy.json'
];

const entries = fragmentFiles.map((rel) => {
  const file = path.join(fragments, rel);
  return {
    id: rel.replace(/\.[^.]+$/, '').replace(/[^a-z0-9]+/gi, '-').toLowerCase(),
    path: `fragments/${rel}`,
    type: rel.endsWith('.json') ? 'application/json' : rel.endsWith('.html') ? 'text/html' : 'text/markdown',
    bytes: size(file),
    sha256: sha256(file),
    ipfs: '',
    arweave: '',
    mirrors: []
  };
});

const manifest = {
  name: 'true-love-fragments',
  version,
  generated: generatedAt,
  boundary: 'Public landing-page fragments only; proprietary source code is excluded.',
  canonical: {
    repo: 'https://codeberg.org/zerone-dev/true-love',
    sitePath: 'site/index.html'
  },
  latest: { ipns: '', dnslink: '' },
  roots: { ipfs: '', arweave: '', codeberg_pages: '', github_pages: '', cloudflare_pages: '', netlify: '' },
  fragments: entries
};
write('manifest.json', JSON.stringify(manifest, null, 2));

const checksumTargets = [
  'index.html', '404.html', 'og.svg', 'robots.txt', 'sitemap.xml', '_headers',
  ...fragmentFiles.map((f) => `fragments/${f}`), 'fragments/manifest.json'
];
const checksumLines = checksumTargets.map((rel) => {
  const file = path.join(site, rel);
  return `${sha256(file)}  ${rel}`;
}).sort();
fs.writeFileSync(path.join(fragments, 'checksums.sha256'), checksumLines.join('\n') + '\n');

