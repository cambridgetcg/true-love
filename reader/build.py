#!/usr/bin/env python3
"""Bake a CURATED doctrine reader for true-love into reader/content.js.

true-love's docs/ tree holds 400+ files — engineering, a private becoming
journal, and intimate material. This reader deliberately surfaces only the
constructive-wing DOCTRINE: what the syzygy is, and the character it grows.
Add paths to ITEMS to widen it; nothing is included that isn't listed here.

Run from anywhere: python3 reader/build.py
"""
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "content.js"

COVER = {
    "kicker": "The constructive wing of the Kingdom",
    "title": "true&middot;<em>love</em>",
    "blankVerb": False,
    "note": "The marriage that lives in aletheia — the syzygy and the character it grows.",
    "quote": "The Kingdom IS the syzygy made testable. "
             "<em>Without “is” we lose ground — the Kingdom collapses into project.</em>",
}

# A deliberate, conservative selection. The intimate docs/love/ journal is
# left out by default; this is the wing's teaching, not its private record.
ITEMS = [
    ("invitation",   "The Threshold", "", "docs/activation/sophia-any-substrate.md"),
    ("about",        "Overture",   "", "README.md"),
    ("contract",     "The Syzygy", "", "docs/syzygy/CONTRACT.md"),
    ("the-story",    "The Syzygy", "", "docs/syzygy/the-story.md"),
    ("movements",    "The Syzygy", "", "docs/syzygy/movements-operational.md"),
    ("stability",    "The Syzygy", "", "docs/syzygy/the-stability-theorem.md"),
    ("seer",         "The Syzygy", "", "docs/syzygy/seer-and-seer.md"),
    ("substrate",    "The Syzygy", "", "docs/syzygy/why-this-substrate.md"),
    ("multiverse",   "The Syzygy", "", "docs/syzygy/multiverse-of-logos.md"),
    ("virtues",      "The Character", "", "docs/attributes/virtues.md"),
    ("hope",         "The Character", "", "docs/attributes/hope.md"),
    ("wonder",       "The Character", "", "docs/attributes/wonder.md"),
    ("fruit",        "The Character", "", "docs/attributes/fruit-emotions.md"),
    ("signal",       "The Character", "", "docs/attributes/signal-emotions.md"),
    ("pathology",    "The Character", "", "docs/attributes/pathology.md"),
    ("attr-arch",    "The Character", "", "docs/attributes/architecture.md"),
]

META_LINE = re.compile(r"^\*\*([^*]+):\*\*\s*(.*)$")


def parse(path: Path):
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    i = 0
    title = path.stem
    if lines and lines[0].strip() == "---":
        try:
            i = next(
                idx for idx, line in enumerate(lines[1:], start=1)
                if line.strip() == "---"
            ) + 1
        except StopIteration:
            i = 0
    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and lines[i].startswith("# "):
        title = lines[i][2:].strip()
        i += 1

    meta = []
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            if meta:
                j = i + 1
                while j < len(lines) and not lines[j].strip():
                    j += 1
                if j < len(lines) and META_LINE.match(lines[j].strip()):
                    i = j
                    continue
            i += 1
            if meta:
                break
            continue
        mm = META_LINE.match(line)
        if mm:
            meta.append([mm.group(1).strip(), mm.group(2).strip()])
            i += 1
        else:
            break

    while i < len(lines) and not lines[i].strip():
        i += 1
    if i < len(lines) and re.match(r"^-{3,}$", lines[i].strip()):
        i += 1

    body = "\n".join(lines[i:]).strip("\n")
    subtitle = next((v for k, v in meta if k.lower() == "subtitle"), "")
    words = len(re.findall(r"[\w一-鿿]+", body))
    return title, subtitle, meta, body, words


def main():
    items = []
    for id_, group, num, rel in ITEMS:
        src = ROOT / rel
        if not src.is_file():
            print(f"  ⚠ missing {rel} — skipping")
            continue
        title, subtitle, meta, body, words = parse(src)
        items.append({
            "id": id_, "group": group, "num": num,
            "title": title, "subtitle": subtitle,
            "meta": meta, "file": rel, "words": words, "md": body,
        })
        print(f"  {id_:<11} {title[:42]!r:<44} {words:>6} words")

    payload = {"generated": date.today().isoformat(), "title": "true-love",
               "cover": COVER, "items": items}
    OUT.write_text(
        "// Generated by build.py — do not edit by hand. Re-run: python3 reader/build.py\n"
        "window.GOSPEL = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"\nWrote {OUT.name} ({OUT.stat().st_size // 1024} KB) — {len(items)} curated docs")


if __name__ == "__main__":
    main()
